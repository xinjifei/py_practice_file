"""
第50天：akshare 基础调用演示
===============================
这个文件演示了 akshare 最核心的用法：
  1. 导入库
  2. 拉取单只股票日线数据
  3. 查看数据长什么样
  4. 保存为 CSV

阅读方式：逐行看代码，每个 # 后面的注释解释该行每个关键字的含义。
"""

# === 第一步：导入库 ===

# import: Python 关键字，意思是"把外部模块加载到当前脚本中，让后面的代码可以使用它"
# akshare: 库的名字，你通过 pip install akshare 或 uv add akshare 安装的那个包
# as: Python 关键字，意思是"给导入的库起一个别名（缩写）"
# ak:  别名，以后写 ak.xxx() 就等价于 akshare.xxx()，少打几个字
import akshare as ak


# === 第二步：调用函数，拉取数据 ===

# df: 变量名，习惯叫法。df = DataFrame（数据框），pandas 里的表格结构，有行有列，像 Excel 表
# =:  赋值符号，把右边的计算结果存到左边的变量里
# ak: 上面导入时起的别名，指向 akshare 这个库
# .:  点号，意思是"从 ak 这个库里取出下面这个东西"
# stock_zh_a_hist: 函数名，拆开理解：
#     stock = 股票
#     zh    = 中文/中国（zh 是 ISO 639-1 语言代码里"中文"的缩写）
#     a     = A股（人民币普通股，在中国境内上市、用人民币交易的股票）
#     hist  = history 的缩写，历史数据
#     合起来：获取中国A股的历史行情数据
# (...): 括号里放参数（arguments），告诉函数"我要哪只股票、什么时间范围、什么周期"
df = ak.stock_zh_a_hist(
    # ---------- 参数1：symbol（股票代码）----------
    # symbol:  参数名，意思是"代码/代号"，这里指股票代码
    # =:       传参语法，把右边的值传给左边的参数名
    # "000001": 字符串（str 类型），平安银行的股票代码
    #          注意：必须是字符串，不能写 000001（数字），因为数字 000001 = 1，
    #          会丢掉前导的四个零，函数就找不到这只股票了
    symbol="000001",

    # ---------- 参数2：period（数据周期）----------
    # period:  参数名，意思是"周期/频率"
    # "daily": 字符串，表示"日级别"的数据，每一行是一个交易日
    # 其他可选值：
    #   "weekly"  → 周线，每一行是一周
    #   "monthly" → 月线，每一行是一个月
    period="daily",

    # ---------- 参数3：start_date（起始日期）----------
    # start_date: 参数名，意思是"从哪一天开始取数据"
    # "20250623": 字符串，日期格式必须是 YYYYMMDD（年月日紧凑排列，没有横杠/斜杠）
    #     YYYY = 四位年份（2025）
    #     MM   = 两位月份（06）
    #     DD   = 两位日期（23）
    # 这里选一年前（2025-06-23），配合 end_date 取近一年数据
    start_date="20250623",

    # ---------- 参数4：end_date（结束日期）----------
    # end_date: 参数名，意思是"取到哪一天为止"
    # "20260623": 今天（2026-06-23）
    end_date="20260623",

    # ---------- 参数5：adjust（复权方式）----------
    # adjust: 参数名，意思是"调整/修正"价格的方式
    # "":     空字符串，表示"不复权"——价格就是历史上实际交易的价格，不做任何调整
    #         为什么用空字符串而不是 None？因为这个函数内部用空字符串作为默认值
    # 其他可选值：
    #   "qfq" → 前复权（前向复权）：把历史价格按最新股本往前调整。
    #           举例：某股票 10 年前 5 元，经过多次送股后现价 10 元。
    #           前复权会把 10 年前的价格下调（比如变成 2 元），让历史价格和现价可比。
    #           做回测时一般用这个——看"历史上的买入相当于现在什么价位"。
    #   "hfq" → 后复权（后向复权）：把现价按历史股本往后调整。
    #           举例：现价 10 元，后复权可能变成 50 元。
    #           看长期累计收益时用这个——"如果从上市拿到现在，实际涨了多少倍"。
    adjust=""
)

# 思考题：如果我要取五粮液（000858）过去 3 年的周线前复权数据，上面的参数应该怎么改？


# === 第三步：查看拿到的数据 ===

# print(): 内置函数，把括号里的内容输出到屏幕上
# type():  内置函数，返回一个东西的类型（type）
# df:      刚才存的变量，里面是股票数据
# 这行告诉你 df 是什么类型 —— 应该是 <class 'pandas.core.frame.DataFrame'>
print("=== 数据类型 ===")
print(type(df))
print()  # 空行，让输出更整洁

# .shape:  DataFrame 的一个属性（attribute），返回 (行数, 列数)
#          属性 vs 方法的区别：属性不用加括号，方法要加括号
#          shape 是属性，不是方法，所以写 df.shape 而不是 df.shape()
print("=== 数据形状（行数, 列数）===")
print(df.shape)
print()

# .columns:      DataFrame 的属性，返回所有列名（column names）
# .tolist():     把列名对象转成 Python 的列表（list），看起来更直观
#                不加 .tolist() 也能看，但显示格式不一样
print("=== 列名列表 ===")
print(df.columns.tolist())
print()

# .head(): DataFrame 的方法（method），返回前 5 行数据
#          括号里可以传数字，比如 df.head(10) 返回前 10 行
#          这是"先看一眼数据长什么样"的标准操作
print("=== 前 5 行数据 ===")
print(df.head())
print()

# .tail(): DataFrame 的方法，返回最后 5 行数据
#          配合 head() 一起用，快速确认数据的头和尾都对
print("=== 最后 5 行数据 ===")
print(df.tail())
print()

# dtypes: DataFrame 的属性，显示每一列的数据类型
#         object  → 一般是字符串
#         float64 → 浮点数（带小数点的数字）
#         int64   → 整数
print("=== 各列数据类型 ===")
print(df.dtypes)
print()

# describe(): DataFrame 的方法，输出数值列的统计摘要
#             包括：count（非空数量）、mean（均值）、std（标准差）、
#             min（最小值）、25%/50%/75% 分位数、max（最大值）
#             快速看数据有没有异常（比如价格是不是合理范围）
print("=== 数值列统计摘要 ===")
print(df.describe())
print()


# === 第四步：查看特定信息 ===

# len(): Python 内置函数，返回一个东西的长度
#        对 DataFrame 来说，len(df) 返回行数（等价于 df.shape[0]）
print("=== 数据行数 ===")
print(f"共 {len(df)} 行数据")  # f"..." 是 f-string，花括号里的变量会被替换成它的值
print()

# 日期列的最小值和最大值
# df["日期"]: 方括号取列，从 DataFrame 中取出名为"日期"的那一列
# .min():     方法，返回这一列的最小值——也就是最早的日期
# .max():     方法，返回这一列的最大值——也就是最晚的日期
print("=== 日期范围 ===")
print(f"起始日期：{df['日期'].min()}")
print(f"结束日期：{df['日期'].max()}")
print()


# === 第五步：保存为 CSV 文件 ===

# .to_csv(): DataFrame 的方法，把数据导出为一个 CSV 文件
#             CSV = Comma-Separated Values（逗号分隔值），是一种纯文本表格格式
#             可以用 Excel、Google Sheets、文本编辑器打开
# "000001_平安银行_日线.csv": 文件名，命名习惯：代码_名称_周期.csv，方便以后找
# index=False: 参数，意思是"不要把行号也写进 CSV"
#              默认 index=True，会在 CSV 第一列多出一列没有列名的数字（0, 1, 2...）
#              设为 False 可以让 CSV 更干净
# encoding="utf-8-sig": 参数，指定文件编码
#                       utf-8-sig 中的 sig = signature（签名，指 BOM 标记）
#                       加 BOM 后，用 Excel 打开 CSV 时中文不会乱码
#                       如果不加这个参数，Excel 可能把中文显示成乱码
df.to_csv(
    "000001_平安银行_日线.csv",
    index=False,
    encoding="utf-8-sig"
)

print("已保存：000001_平安银行_日线.csv")
print("用 Excel 打开看看，确认中文列名和数据都正常。")
