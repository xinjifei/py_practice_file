"""
理解 @ 装饰器 —— 最简示例

运行方式: uv run 装饰器_练习题.py
"""

# ============================================================
#   第一步：手写一个最简单的"装饰器"
#   它接收一个函数，在函数前后打印东西，然后返回
# ============================================================

def 给函数加个框(原函数):
    """装饰器：接收一个函数，返回一个"加强版"的函数"""
    def 加强版():
        print("███████ 开始 ███████")
        原函数()                       # 调用原来的函数
        print("███████ 结束 ███████")
    return 加强版                      # 把加强版还回去


# ============================================================
#   第二步：对比 —— 用 @ 和不用 @ 是一样的
# ============================================================

print("===== 方式A：不用 @，手动套壳 =====")

def 你好():
    print("你好世界！")

# 手动包一层
包装后的你好 = 给函数加个框(你好)
包装后的你好()          # 调用的是加强版


print("\n===== 方式B：用 @，完全一样 =====")

@给函数加个框                 # 等同于: 再见 = 给函数加个框(再见)
def 再见():
    print("再见世界！")

再见()                       # 直接调，但实际跑的是加强版


print("\n===== @ 就是语法糖 =====")
print("@给函数加个框 写在函数头顶 = 给函数加个框(函数名)")
print("两种写法完全等价")
