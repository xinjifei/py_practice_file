"""
第四课：散点图加颜色和大小
同一个 scatter，多传两个参数，第三个维度的信息就出来了。
"""
import plotly.express as px

# 数据：5 个城市，X=人均收入，Y=平均寿命，颜色=地区，大小=人口
data = {
    "城市": ["北京", "上海", "广州", "成都", "拉萨"],
    "人均收入(万)": [18, 19, 15, 10, 6],
    "平均寿命(岁)": [82, 83, 80, 78, 72],
    "地区": ["华北", "华东", "华南", "西南", "西南"],
    "人口(万)": [2189, 2487, 1868, 2127, 87],
}

fig = px.scatter(
    x=data["人均收入(万)"],
    y=data["平均寿命(岁)"],
    color=data["地区"],          # 颜色按地区分组 → 图例自动生成
    size=data["人口(万)"],       # 气泡大小 → 第三个维度
    title="收入 vs 寿命（气泡大小=人口）",
    hover_name=data["城市"],     # 悬停时显示城市名
)
fig.show()
