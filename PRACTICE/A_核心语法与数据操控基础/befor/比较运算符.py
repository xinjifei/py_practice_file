#运算符：< > <= >= != ==;依次为，小于、大于、小于等于、大于等于、不等于
#/等等于。
#比较运算符前后需有空格
#运算符的输出格式为 布尔
#输入式（【定义变量名】【空格】【变量名1】【比较运算符】【空格】【变量名2】

#例
a=1
b=2

#等于
jieguo1=a == b
print(f'jieguo1={jieguo1},type(jieguo1)={type(jieguo1)}')

#不等于
jieguo2=a != b
print(f'jieguo2={jieguo2},type(jieguo2)={type(jieguo2)}')

#小于
jieguo3=a < b
print(f'jieguo3={jieguo3},type(jieguo3)={type(jieguo3)}')


