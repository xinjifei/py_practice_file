#int类型变量值（整形）
int1=1
print(f'int1={int1},type(int1)={type(int1)}')

#float类型变量值（浮点）
flaot=1.5
print(f'flaot1={flaot},type(flaot)={type(flaot)}')

#bool类型变量值（布尔）
jiechu=False
print(f'jiechu={jiechu},type(jiechu)={type(jiechu)}')

#strin类型变量值（字符串）
strin1='''
消灭人类暴政！
世界属于三体！
'''
print(f'strin1={strin1},type(strin1)={type(strin1)}')

#list类型变量值（列表）
names=['nms1','nms2','nms3']
print(f'names={names},type(names)={type(names)}')

#tuple类型变量（元组）
name2=('tuple1','tuple2','tuple3')
print(f'name2={name2},type(name2)={type(name2)}')

#set类型变量值（集合）
set={'set1','set2','set3'}
print(f'set={set},type(set)={type(set)}')

#dict类型变量值（字典）
dict={'xingbie':'nan','shengao':'178','tizhong':'130'}
print(f'dict={dict},type(dict)={type(dict)}')
